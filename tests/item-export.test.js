import test from 'node:test';
import assert from 'node:assert/strict';
import { ITEMS } from '../src/inventory.js';
import { itemRows, javaItemsSource } from '../tools/registry/export.mjs';

test('every registered item is exported once, in order, with its gameplay fields', () => {
  const rows = itemRows(ITEMS);
  assert.equal(rows.length, ITEMS.size);
  assert.deepEqual(rows.map(r => r.id), [...ITEMS.keys()]);
  const byId = id => rows.find(r => r.id === id);
  assert.equal(byId('stone').isBlock, true); assert.equal(byId('stone').maxStack, 64);
  assert.equal(byId('water'), undefined, 'water is not an inventory item');
  assert.equal(byId('stick').isBlock, false);
  const pickaxe = byId('stone.pickaxe');
  assert.deepEqual([pickaxe.toolType, pickaxe.toolSpeed, pickaxe.toolLevel, pickaxe.durability, pickaxe.maxStack], ['pickaxe', 4, 1, 131, 1]);
  assert.equal(byId('shears').toolType, 'shears');
  assert.deepEqual([byId('raw.porkchop').foodHunger, byId('raw.porkchop').foodSaturation], [3, 1.8]);
  assert.deepEqual([byId('cooked.porkchop').foodHunger, byId('cooked.porkchop').foodSaturation], [8, 12.8]);
  assert.deepEqual([byId('bucket').maxStack, byId('water.bucket').maxStack], [16, 1]);
  assert.equal(byId('stick').toolType, ''); assert.equal(byId('stick').durability, 0); assert.equal(byId('stick').foodHunger, -1);
});

test('generated Java items are deterministic and list every item', () => {
  const a = javaItemsSource(itemRows(ITEMS));
  assert.equal(a, javaItemsSource(itemRows(ITEMS)));
  for (const id of ITEMS.keys()) assert.ok(a.includes(`"${id}"`), id);
  assert.match(a, /Generated by tools\/registry\/generate\.mjs/);
});

test('items the table cannot represent are refused', () => {
  assert.throws(() => itemRows(new Map([['x', { id: 'x', maxStack: 1, tool: { type: 'pickaxe', speed: 1 } , durability: 0.5 }]])), /x.*durability/);
});
