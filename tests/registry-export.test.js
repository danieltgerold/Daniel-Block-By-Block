import test from 'node:test';
import assert from 'node:assert/strict';
import { BLOCK_TYPES } from '../src/block-types.js';
import { blockRows, javaBlocksSource, classifyDrops } from '../tools/registry/export.mjs';

test('every registered block is exported once with its gameplay fields', () => {
  const rows = blockRows(BLOCK_TYPES);
  assert.equal(rows.length, BLOCK_TYPES.size);
  assert.deepEqual(rows.map(r => r.id), [...BLOCK_TYPES.keys()], 'registration order is kept');
  const stone = rows.find(r => r.id === 'stone');
  assert.equal(stone.shape, 'cube'); assert.equal(stone.requiresTool, true); assert.equal(stone.preferredTool, 'pickaxe');
  assert.equal(stone.dropRule, 'list'); assert.deepEqual(stone.drops, [{ id: 'cobblestone', count: 1 }]);
  const bedrock = rows.find(r => r.id === 'bedrock');
  assert.equal(bedrock.hardness, -1); assert.equal(bedrock.breakTicks, Infinity);
  assert.equal(rows.find(r => r.id === 'oak.slab').dropRule, 'slab');
  assert.equal(rows.find(r => r.id === 'dirt').dropRule, 'self');
  assert.equal(rows.find(r => r.id === 'stone.slab').dropRule, 'slab');
  assert.equal(rows.find(r => r.id === 'stone.stairs').dropRule, 'self', 'a function that always returns the block itself is just self');
  assert.equal(rows.find(r => r.id === 'stone.wall').dropRule, 'self');
  const lapis = rows.find(r => r.id === 'lapis.ore'), redstone = rows.find(r => r.id === 'redstone.ore'), coal = rows.find(r => r.id === 'coal.ore');
  assert.deepEqual([lapis.dropRule, lapis.drops[0].id, lapis.drops[0].count, lapis.dropMax], ['range', 'lapis.lazuli', 4, 8]);
  assert.deepEqual([redstone.dropRule, redstone.drops[0].id, redstone.drops[0].count, redstone.dropMax], ['range', 'redstone.dust', 4, 5]);
  assert.deepEqual([coal.dropRule, coal.drops], ['list', [{ id: 'coal', count: 1 }]]);
  assert.equal(rows.find(r => r.id === 'glass').dropRule, 'list'); assert.deepEqual(rows.find(r => r.id === 'glass').drops, []);
  assert.equal(rows.find(r => r.id === 'sand').falling, true);
  assert.ok(rows.find(r => r.id === 'oak.log').tags.includes('wood.logs'));
});

test('block default states are exported as ordered keys with canonical string values', () => {
  const rows = blockRows(BLOCK_TYPES), by = id => rows.find(r => r.id === id);
  assert.deepEqual([by('oak.door').stateKeys, by('oak.door').stateValues], [['facing', 'hinge', 'open', 'half'], ['north', 'left', 'false', 'lower']]);
  assert.deepEqual([by('furnace').stateKeys, by('furnace').stateValues], [['facing', 'lit'], ['north', 'false']]);
  assert.deepEqual([by('oak.log').stateKeys, by('oak.log').stateValues], [['axis'], ['y']]);
  assert.deepEqual([by('oak.leaves').stateKeys, by('oak.leaves').stateValues], [['persistent', 'distance'], ['true', '7']]);
  assert.deepEqual([by('farmland').stateKeys, by('farmland').stateValues], [['moisture', 'dryTicks'], ['0', '0']]);
  assert.deepEqual(by('oak.stairs').stateKeys, ['facing', 'half', 'shape']);
  assert.deepEqual([by('water').stateKeys, by('water').stateValues], [[], []], 'water level/falling live on the world block');
  assert.deepEqual(by('stone').stateKeys, []);
});

test('state values the table cannot represent are refused', () => {
  const block = state => new Map([['x', { id: 'x', collisionShape: 'cube', solid: true, opaque: true, tags: [], drops: 'self', defaultState: state }]]);
  assert.throws(() => blockRows(block({ mystery: 1 })), /x.*mystery/);
  assert.throws(() => blockRows(block({ axis: { nested: true } })), /x.*axis/);
  assert.throws(() => blockRows(block({ moisture: 1.5 })), /x.*moisture/);
});

test('drop rules that are functions are recognised by behaviour, and unknown ones are refused', () => {
  const slab = ({ block }) => [{ id: block.id, count: block.state?.type === 'double' ? 2 : 1 }];
  assert.equal(classifyDrops({ id: 'x.slab', drops: slab }).dropRule, 'slab');
  assert.deepEqual(classifyDrops({ id: 'fixed', drops: () => [{ id: 'dirt', count: 7 }] }), { dropRule: 'list', drops: [{ id: 'dirt', count: 7 }], dropMax: 0 });
  assert.throws(() => classifyDrops({ id: 'weird', drops: ({ random }) => [{ id: 'dirt', count: Math.floor(random() ** 2 * 10) }] }), /weird.*drop rule/);
});

test('unknown collision shapes are refused instead of silently exported', () => {
  const map = new Map([['x', { id: 'x', collisionShape: 'hexagon', solid: true, opaque: true, tags: [], drops: 'self' }]]);
  assert.throws(() => blockRows(map), /hexagon/);
});

test('generated Java source is deterministic and lists every block', () => {
  const a = javaBlocksSource(blockRows(BLOCK_TYPES)), b = javaBlocksSource(blockRows(BLOCK_TYPES));
  assert.equal(a, b);
  for (const id of BLOCK_TYPES.keys()) assert.ok(a.includes(`"${id}"`), id);
  assert.match(a, /Generated by tools\/registry\/generate\.mjs/);
});
