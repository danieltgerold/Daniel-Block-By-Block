import test from 'node:test';
import assert from 'node:assert/strict';
import { ITEMS } from '../src/inventory.js';
import { RECIPES } from '../src/recipes.js';
import { SMELTING, FUELS } from '../src/smelting.js';
import { itemRows, recipeRows, javaRecipesSource, smeltingRows, fuelRows, recipesCsv } from '../tools/registry/export.mjs';

test('items export their tags so tag ingredients can match in Java', () => {
  const rows = itemRows(ITEMS);
  assert.deepEqual(rows.find(r => r.id === 'oak.planks').tags, ['wood.planks', 'wood.oak']);
  assert.deepEqual(rows.find(r => r.id === 'stick').tags, []);
});

test('every recipe is exported once, in order, with normalised cells', () => {
  const rows = recipeRows(RECIPES, ITEMS);
  assert.equal(rows.length, RECIPES.recipes.size);
  assert.deepEqual(rows.map(r => r.id), [...RECIPES.recipes.keys()]);
  const sticks = rows.find(r => r.id === 'sticks');
  assert.deepEqual([sticks.type, sticks.width, sticks.height, sticks.grids, sticks.output], ['shaped', 1, 2, [2, 3], { id: 'stick', count: 4 }]);
  assert.deepEqual(sticks.cells, [{ kind: 'tag', value: 'wood.planks', count: 1 }, { kind: 'tag', value: 'wood.planks', count: 1 }]);
  const planks = rows.find(r => r.id === 'oak.planks');
  assert.equal(planks.type, 'shapeless'); assert.equal(planks.width, 0);
  assert.deepEqual(planks.cells, [{ kind: 'item', value: 'oak.log', count: 1 }]);
  const stairs = rows.find(r => r.id === 'oak.stairs');
  assert.deepEqual([stairs.width, stairs.height, stairs.cells.filter(Boolean).length, stairs.cells[1]], [3, 3, 6, null], 'empty pattern cells are null');
  assert.deepEqual(rows.find(r => r.id === 'bucket').grids, [3]);
  assert.equal(rows.find(r => r.id === 'stone.pickaxe').category, 'tools');
  for (const row of rows) assert.ok(ITEMS.has(row.output.id), `${row.id} output exists`);
});

test('smelting and fuel tables are exported in order', () => {
  const smelting = smeltingRows(SMELTING), fuels = fuelRows(FUELS);
  assert.deepEqual(smelting[0], { id: 'sand.glass', input: 'sand', output: 'glass', count: 1, ticks: 200 });
  assert.equal(smelting.length, SMELTING.size);
  assert.deepEqual(fuels.find(f => f.id === 'coal'), { id: 'coal', ticks: 1600 });
  assert.equal(fuels.length, FUELS.size);
});

test('unrepresentable recipes are refused, and the Java source is deterministic', () => {
  const group = new Map([['x', { id: 'x', type: 'shapeless', cells: [{ group: 'nope', count: 1 }], width: null, height: null, grids: [2], mirror: true, category: 'c', output: { id: 'dirt', count: 1 } }]]);
  assert.throws(() => recipeRows({ recipes: group }, ITEMS), /x.*group/);
  const a = javaRecipesSource(recipeRows(RECIPES, ITEMS), smeltingRows(SMELTING), fuelRows(FUELS));
  assert.equal(a, javaRecipesSource(recipeRows(RECIPES, ITEMS), smeltingRows(SMELTING), fuelRows(FUELS)));
  assert.match(a, /Generated by tools\/registry\/generate\.mjs/);
  assert.ok(recipesCsv(recipeRows(RECIPES, ITEMS)).startsWith('id,type,width,height,grids,mirror,category,outputId,outputCount,cells\n'));
});
