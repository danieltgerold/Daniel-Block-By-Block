// Turns the JS block registry into plain rows, then into Java source. The JS registry stays the source
// of truth; the Java core only ever reads the generated table. Anything the table cannot represent
// (an unknown shape, an unrecognised drop function) stops the export so someone decides what it means.
const SHAPES = new Set(['cube', 'slab', 'stairs', 'door', 'fence', 'wall', 'farmland', 'fluid']);
const RANDOMS = [0, 0.5, 0.999999];

const json = value => JSON.stringify(value);
const sameJson = (a, b) => json(a) === json(b);

/** Classifies a block's drop rule by what it does, not by how it is written. */
export function classifyDrops(definition) {
  const { id, drops } = definition;
  if (drops === 'self') return { dropRule: 'self', drops: [{ id, count: 1 }], dropMax: 0 };
  if (Array.isArray(drops)) return { dropRule: 'list', drops: drops.map(d => ({ id: d.id, count: d.count })), dropMax: 0 };
  if (typeof drops !== 'function') throw new Error(`${id}: unsupported drop rule ${typeof drops}`);
  const probe = (type, random) => drops({ block: { id, definition, state: type ? { type } : {} }, random: () => random });
  const base = probe(undefined, 0);
  const self = [{ id, count: 1 }];
  const constant = RANDOMS.every(r => sameJson(probe(undefined, r), base) && sameJson(probe('double', r), base));
  if (constant) return sameJson(base, self) ? { dropRule: 'self', drops: self, dropMax: 0 }
    : { dropRule: 'list', drops: base.map(d => ({ id: d.id, count: d.count })), dropMax: 0 };
  const double = probe('double', 0);
  if (RANDOMS.every(r => sameJson(probe(undefined, r), self) && sameJson(probe('bottom', r), self)
    && sameJson(probe('double', r), [{ id, count: 2 }])) && double.length === 1) return { dropRule: 'slab', drops: self, dropMax: 0 };
  const low = probe(undefined, 0), high = probe(undefined, RANDOMS[2]), mid = probe(undefined, 0.5);
  if (low.length === 1 && high.length === 1 && low[0].id === high[0].id) {
    const min = low[0].count, max = high[0].count, span = max - min + 1;
    if (span > 1 && mid[0].count === min + Math.floor(0.5 * span)
      && RANDOMS.every(r => probe('double', r)[0].count === probe(undefined, r)[0].count))
      return { dropRule: 'range', drops: [{ id: low[0].id, count: min }], dropMax: max };
  }
  throw new Error(`${id}: unrecognised drop rule; teach tools/registry/export.mjs what it means before exporting`);
}

export function blockRows(blocks) {
  return [...blocks.values()].map(block => {
    if (!SHAPES.has(block.collisionShape)) throw new Error(`${block.id}: unknown collision shape ${block.collisionShape}`);
    const rule = classifyDrops(block);
    if (rule.drops.length > 1) throw new Error(`${block.id}: multi-item drops are not exported yet`);
    return { id: block.id, shape: block.collisionShape, solid: Boolean(block.solid), opaque: Boolean(block.opaque),
      hardness: block.hardness, breakTicks: block.breakTicks, requiresTool: Boolean(block.requiresTool),
      preferredTool: block.preferredTool ?? null, harvestLevel: block.harvestLevel ?? 0, maxStack: block.maxStack,
      falling: Boolean(block.falling), tags: [...block.tags], ...rule };
  });
}

const javaNumber = n => n === Infinity ? 'Double.POSITIVE_INFINITY' : n === -Infinity ? 'Double.NEGATIVE_INFINITY'
  : Number.isInteger(n) ? `${n}.0` : String(n);
const javaString = s => `"${s.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
const DROP_RULES = { self: 'SELF', list: 'LIST', slab: 'SLAB', range: 'RANGE' };

export function javaBlocksSource(rows) {
  const lines = rows.map(r => {
    const drop = r.drops[0];
    return `            new BlockDefinition(${javaString(r.id)}, Shape.${r.shape.toUpperCase()}, ${r.solid}, ${r.opaque}, ${javaNumber(r.hardness)}, ${javaNumber(r.breakTicks)},\n`
      + `                ${r.requiresTool}, ${r.preferredTool === null ? 'null' : javaString(r.preferredTool)}, ${r.harvestLevel}, ${r.maxStack}, ${r.falling},\n`
      + `                DropRule.${DROP_RULES[r.dropRule]}, ${drop ? javaString(drop.id) : 'null'}, ${drop ? drop.count : 0}, ${r.dropMax},\n`
      + `                new String[] {${r.tags.map(javaString).join(', ')}})`;
  });
  return `// Generated by tools/registry/generate.mjs from src/block-types.js. Do not edit; run \`npm run golden\`.\n`
    + `package blockbyblock.core.world.shape;\n\n`
    + `/** Every block the JS registry defines, in registration order. */\n`
    + `final class GeneratedBlocks {\n    private GeneratedBlocks() {}\n\n`
    + `    static BlockDefinition[] all() {\n        return new BlockDefinition[] {\n${lines.join(',\n')}\n        };\n    }\n}\n`;
}

const csvNumber = n => n === Infinity ? 'Infinity' : n === -Infinity ? '-Infinity' : String(n);
export const BLOCK_CSV_HEADER = 'id,shape,solid,opaque,hardness,breakTicks,requiresTool,preferredTool,harvestLevel,maxStack,falling,dropRule,dropId,dropCount,dropMax,tags';
export function blocksCsv(rows) {
  const body = rows.map(r => [r.id, r.shape, +r.solid, +r.opaque, csvNumber(r.hardness), csvNumber(r.breakTicks), +r.requiresTool,
    r.preferredTool ?? '', r.harvestLevel, r.maxStack, +r.falling, r.dropRule, r.drops[0]?.id ?? '', r.drops[0]?.count ?? 0, r.dropMax,
    r.tags.join('|')].join(','));
  return [BLOCK_CSV_HEADER, ...body].join('\n') + '\n';
}
